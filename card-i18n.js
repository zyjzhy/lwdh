  /** 合并补充翻译表（card-en-extra.js 提供的扩展） */
  function getExtra() {
    return (typeof CardEnExtra !== 'undefined') ? CardEnExtra : { labels: {}, tooltips: {} };
  }

  function getLabelMap() {
    var extra = getExtra();
    return (extra.labels && Object.keys(extra.labels).length) ? extra.labels : null;
  }

  /** 翻译一个元素的 data-tooltip */
  function translateTooltip(el) {
    var zh = el.getAttribute('data-tooltip');
    if (!zh) return;
    var map = tooltipMap;
    if (!map[zh]) {
      var extra = getExtra();
      if (extra.tooltips && extra.tooltips[zh]) map = extra.tooltips;
    }
    if (CardI18N._lang === 'en' && map[zh]) {
      el.setAttribute('data-tooltip', map[zh]);
    } else if (CardI18N._lang === 'zh') {
      // 恢复中文：保存原始值
      if (el.dataset.tooltipOrig) {
        el.setAttribute('data-tooltip', el.dataset.tooltipOrig);
      }
    }
  }

  /** 获取卡片可见文字（直接文本节点拼接，忽略 img、badge 等子元素） */
  function getCardLabel(el) {
    var label = el.querySelector('.card-label');
    if (label) return label.textContent.trim();
    var parts = [];
    el.childNodes.forEach(function(node) {
      if (node.nodeType === 3) parts.push(node.nodeValue);
    });
    return parts.join('').replace(/\s+/g, ' ').trim();
  }

  /** 覆写卡片可见文字（保留 badge 等子元素结构） */
  function setCardLabel(el, text) {
    var label = el.querySelector('.card-label');
    if (label) { label.textContent = text; return; }
    var first = null;
    el.childNodes.forEach(function(node) {
      if (node.nodeType === 3) {
        if (!first) first = node;
        else if (node.nodeValue.trim()) node.nodeValue = ' ';
      }
    });
    if (first) {
      first.nodeValue = text;
    } else {
      el.insertBefore(document.createTextNode(text), el.firstChild);
    }
  }

  /** 翻译一个卡片的可见文字 */
  function translateCardLabel(el) {
    var map = getLabelMap();
    if (!map) return;
    if (!el.dataset.labelOrig) {
      el.dataset.labelOrig = getCardLabel(el) || '';
    }
    var zh = el.dataset.labelOrig;
    if (!zh) return;
    if (CardI18N._lang === 'en') {
      if (map[zh]) setCardLabel(el, map[zh]);
    } else if (CardI18N._lang === 'zh') {
      if (map[zh]) setCardLabel(el, zh);
    }
  }

  /** 翻译所有卡片 */
  function translateAllCards(lang) {
    CardI18N._lang = lang;
    document.querySelectorAll('.card[data-tooltip]').forEach(function(el) {
      if (lang === 'en' && !el.dataset.tooltipOrig) {
        el.dataset.tooltipOrig = el.getAttribute('data-tooltip');
      }
      translateTooltip(el);
    });
    // 可见文字仅对卡片本体翻译（跳过“常用推荐”动态区，避免覆盖 JS 渲染内容）
    var labelMapData = getLabelMap();
    if (labelMapData) {
      document.querySelectorAll('.column .card:not([data-frequent-clone])').forEach(function(el) {
        translateCardLabel(el);
      });
    }
  }

  return {
    _lang: 'zh',
    tooltipMap,
    translateAllCards,
  };
